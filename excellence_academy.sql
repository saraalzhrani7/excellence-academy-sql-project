-- =====================================================
-- المتطلب 1: جدول الطلاب المتفوقين (معدل أعلى من 90)
-- =====================================================
CREATE TABLE top_students AS
SELECT * FROM students WHERE gpa > 90;

SELECT * FROM top_students;

-- =====================================================
-- المتطلب 2: جدول الطلاب غير المجتازين (معدل أقل من 60)
-- =====================================================
CREATE TABLE failing_students AS
SELECT * FROM students WHERE gpa < 60;

SELECT * FROM failing_students;

-- =====================================================
-- المتطلب 3: أسماء الطلاب اللي تبدأ بحرف A
-- ملاحظة: بياناتنا أسماء عربية، فالنتيجة متوقع تكون فاضية
-- =====================================================
SELECT student_name FROM students WHERE student_name LIKE 'A%';

-- =====================================================
-- المتطلب 4: أسماء الطلاب اللي فيها 4 خانات بالضبط
-- =====================================================
SELECT student_name FROM students WHERE CHAR_LENGTH(student_name) = 4;

-- =====================================================
-- المتطلب 5: AVG, MAX, MIN مع تسمية واضحة
-- =====================================================
SELECT
    AVG(gpa) AS Average_GPA,
    MAX(gpa) AS Highest_GPA,
    MIN(gpa) AS Lowest_GPA
FROM students;

-- =====================================================
-- المتطلب 6: الطلاب المتفوقين بالمستوى السادس بمعدل = 100
-- ملاحظة: متوقع تكون فاضية لأن أعلى معدل بالبيانات 99.69
-- =====================================================
SELECT student_name FROM students
WHERE level = 6 AND gpa = 100;

-- =====================================================
-- المتطلب 7: طلاب المستوى الأول بعمر بين 15 و16 سنة
-- =====================================================
SELECT * FROM students
WHERE level = 1
AND TIMESTAMPDIFF(YEAR, birth_date, CURDATE()) BETWEEN 15 AND 16;

-- =====================================================
-- المتطلب 8: عدد الطلاب بالمستوى 2
-- =====================================================
SELECT COUNT(*) AS Level2_Count
FROM students
WHERE level = 2;

-- =====================================================
-- المتطلب 9: مسارات الطلاب بدون تكرار
-- =====================================================
SELECT DISTINCT track FROM students;

-- =====================================================
-- المتطلب 10: أسماء المواد بأحرف كبيرة
-- =====================================================
SELECT UPPER(subject_name) AS Subject_Name FROM subjects;

-- =====================================================
-- المتطلب 11: المتوسط الحسابي مقرّب لأقرب عدد أصغر
-- =====================================================
SELECT FLOOR(AVG(gpa)) AS Average_GPA_Rounded
FROM students;

-- =====================================================
-- المتطلب 12: تبديل الجنس من F/M إلى Female/Male
-- =====================================================
ALTER TABLE students MODIFY COLUMN gender VARCHAR(10);

UPDATE students SET gender = REPLACE(gender, 'F', 'Female') WHERE gender = 'F';
UPDATE students SET gender = REPLACE(gender, 'M', 'Male') WHERE gender = 'M';

SELECT DISTINCT gender FROM students;

-- =====================================================
-- المتطلب 13: زيادة معدل الطلاب الأقل من 60 بخمس درجات
-- ملاحظة: كل معدلاتنا فوق 70، فهذا الأمر لن يؤثر على أي صف حاليًا
-- =====================================================
UPDATE students
SET gpa = gpa + 5
WHERE gpa < 60;
